/**
 * Resolve a Lucide icon component by its string name.
 * Returns `undefined` if the icon is not in the map.
 */
export function resolveIcon(name: string): LucideIcon | undefined {
  return ICON_MAP[name];
}

/**
 * A reusable component that renders a Lucide icon by its string name.
 */
export function DynamicIcon({
  name,
  className,
}: {
  name: string;
  className?: string;
}) {
  const ResolvedIcon = resolveIcon(name);
  if (!ResolvedIcon) return null;
  return <ResolvedIcon className={className} aria-hidden="true" />;
}

